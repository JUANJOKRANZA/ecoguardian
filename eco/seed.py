def M(cat, lvl, prompt, correct, wrong, why):
    return {"category": cat, "level": lvl, "qtype": "mcq", "prompt": prompt,
            "payload": {"correct": correct, "wrong": list(wrong)}, "explanation": why}


def T(cat, lvl, statement, value, why):
    return {"category": cat, "level": lvl, "qtype": "tf", "prompt": statement,
            "payload": {"correct": bool(value)}, "explanation": why}


def P(cat, lvl, prompt, pairs, why):
    return {"category": cat, "level": lvl, "qtype": "match", "prompt": prompt,
            "payload": {"pairs": [list(p) for p in pairs]}, "explanation": why}


